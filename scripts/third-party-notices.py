#!/usr/bin/env python3
"""Write the license texts of every crate linked into the sigsieve binary.

Usage: third-party-notices.py [--target TRIPLE] OUTPUT

Uses `cargo metadata --locked` (crate sources must already be downloaded,
e.g. by a build) and collects LICENSE*/COPYING*/NOTICE* files from each
normal (non-dev, non-build) dependency reachable from `sigsieve`. Fails if a
dependency ships no license file, so a release archive is never built with
incomplete notices.
"""

import json
import pathlib
import subprocess
import sys

NAMES = ("license", "licence", "copying", "notice")


def main() -> int:
    args = sys.argv[1:]
    target = []
    if args[:1] == ["--target"]:
        target = ["--filter-platform", args[1]]
        args = args[2:]
    if len(args) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    meta = json.loads(
        subprocess.run(
            ["cargo", "metadata", "--locked", "--format-version", "1", *target],
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    )
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = next(p["id"] for p in meta["packages"] if p["name"] == "sigsieve")

    # Normal dependencies only: build scripts and proc-macros are not linked.
    seen, todo = set(), [root]
    while todo:
        node = nodes[todo.pop()]
        for dep in node["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]) and dep["pkg"] not in seen:
                if "proc-macro" in packages[dep["pkg"]]["targets"][0]["kind"]:
                    continue
                seen.add(dep["pkg"])
                todo.append(dep["pkg"])

    out, missing = [], []
    for pid in sorted(seen, key=lambda i: (packages[i]["name"], packages[i]["version"])):
        p = packages[pid]
        src = pathlib.Path(p["manifest_path"]).parent
        files = sorted(
            f for f in src.iterdir() if f.is_file() and f.name.lower().startswith(NAMES)
        )
        if not files:
            missing.append(f'{p["name"]} {p["version"]}')
            continue
        out.append(f'{"=" * 78}\n{p["name"]} {p["version"]} ({p["license"]})\n{"=" * 78}\n')
        for f in files:
            out.append(f"--- {f.name} ---\n{f.read_text(errors='replace').rstrip()}\n\n")
    if missing:
        print("no license file in: " + ", ".join(missing), file=sys.stderr)
        return 1
    header = (
        "Third-party license notices for the sigsieve binary\n"
        f"({len(seen)} crates linked into it; generated by scripts/third-party-notices.py)\n\n"
    )
    pathlib.Path(args[0]).write_text(header + "".join(out))
    print(f"{len(seen)} crates", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
